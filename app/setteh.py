DISCLAIMER = ("این توصیه‌ها عمومی و آموزشی و بر پایه اصول حفظ‌الصحه در طب سنتی ایرانی است و "
              "جایگزین مشاوره، تشخیص یا درمان پزشک نیست.")

def generate(hc_sign, wd_sign):
    keys = []
    if hc_sign: keys.append("hot" if hc_sign > 0 else "cold")
    if wd_sign: keys.append("wet" if wd_sign > 0 else "dry")
    keys = keys or ["balanced"]
    items = {t: [ADVICE[k][i] for k in keys] for i, t in enumerate(SIX)}
    lines = [f"{i}. {t}: " + "؛ ".join(v) for i, (t, v) in enumerate(items.items(), 1)]
    return "\n".join(lines) + "\n\n" + DISCLAIMER
