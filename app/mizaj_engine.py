NAMES = {
    (1, -1): "صفراوی (گرم و خشک)", (1, 1): "دموی (گرم و تر)",
    (-1, 1): "بلغمی (سرد و تر)", (-1, -1): "سوداوی (سرد و خشک)",
    (1, 0): "گرم (بین دموی و صفراوی)", (-1, 0): "سرد (بین بلغمی و سوداوی)",
    (0, 1): "تر (بین دموی و بلغمی)", (0, -1): "خشک (بین صفراوی و سوداوی)",
    (0, 0): "معتدل",
}

def current_season(today=None):
    """فصل تقریبی بر اساس ماه میلادی."""
    m = (today or date.today()).month
    return "بهار" if m in (3, 4, 5) else "تابستان" if m in (6, 7, 8) else "پاییز" if m in (9, 10, 11) else "زمستان"

SEASON_ADJ = {"بهار": (0.05, 0.10), "تابستان": (0.15, -0.05), "پاییز": (-0.05, -0.10), "زمستان": (-0.15, 0.10)}

def _age_adj(age):
    if age < 20: return (0.10, 0.15)
    if age <= 40: return (0.0, 0.0)
    if age <= 60: return (-0.05, -0.10)
    return (-0.15, -0.20)

def _sign(x, t=0.15):
    return 0 if abs(x) < t else (1 if x > 0 else -1)

def evaluate(answers, age, gender, season=None):
    """answers: فهرست ۲۴ عدد (اندیس گزینه‌ی انتخاب‌شده برای هر سؤال)."""
    if len(answers) != len(QUESTIONS):
        raise ValueError("تعداد پاسخ‌ها باید ۲۴ باشد")
    sums = {"HC": 0, "WD": 0}; cnt = {"HC": 0, "WD": 0}
    for (axis, _, opts), a in zip(QUESTIONS, answers):
        sums[axis] += opts[a][1]; cnt[axis] += 1
    hc, wd = sums["HC"] / cnt["HC"], sums["WD"] / cnt["WD"]
    season = season or current_season()
    for dh, dw in (_age_adj(age), SEASON_ADJ[season], ((-0.05, 0.05) if gender in ("زن", "female") else (0, 0))):
        hc += dh; wd += dw
    hc, wd = max(-1, min(1, hc)), max(-1, min(1, wd))
    s = max(abs(hc), abs(wd))
    degree = "خفیف" if s < 0.35 else "متوسط" if s < 0.6 else "شدید"
    hs, ws = _sign(hc), _sign(wd)
    return {"hc": round(hc, 3), "wd": round(wd, 3), "hc_sign": hs, "wd_sign": ws,
            "mizaj": NAMES[(hs, ws)], "degree": degree if (hs or ws) else "-", "season": season}
